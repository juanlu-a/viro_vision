/**
 * Generates `src/global.css` from `src/constants/colors.js`.
 *
 * It exists so Tailwind classes are written **once**: `bg-surface` and not
 * `bg-surface dark:bg-dark-surface`. The trick is that the colour is not a fixed hex but a CSS
 * variable. Since 2026-09-14 (ADR 0010) the app ships dark only, so `:root` carries the dark palette
 * and there is no `.dark` class to toggle: no provider has to push a scheme into NativeWind, and a
 * frame can never paint light by mistake. The light palette stays in `colors.js` as the brand's
 * reference, verified by `theme.test.ts`, and is not emitted here.
 *
 * It is generated instead of hand-written because otherwise there would be a second copy of the
 * palette, which is exactly what `colors.js` exists to prevent. Run `npm run theme:css` after
 * touching colours.
 *
 * `overlay` is left out of the triplet scheme: it is already an rgba with its own transparency, and
 * Tailwind needs loose `r g b` to be able to apply its own alpha channel.
 */
const fs = require('node:fs');
const path = require('node:path');

const { Colors } = require('../src/constants/colors');

/** `#0E2B4F` → `14 43 79`, which is what Tailwind expects so it can compose alpha. */
function toTriplet(hex) {
  const h = hex.replace('#', '');
  const n = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return n.join(' ');
}

function variables(palette, indent) {
  return Object.entries(palette)
    .filter(([, value]) => value.startsWith('#'))
    .map(([name, value]) => `${indent}--color-${kebab(name)}: ${toTriplet(value)};`)
    .join('\n');
}

function kebab(name) {
  return name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

const css = `/* GENERATED BY scripts/generate-theme-css.js — do not edit by hand.
   The palette lives in src/constants/colors.js. Regenerate with: npm run theme:css */
@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {
  :root {
${variables(Colors.dark, '    ')}
  }
}
`;

const target = path.join(__dirname, '..', 'src', 'global.css');
fs.writeFileSync(target, css);
console.log(`global.css generated with ${Object.keys(Colors.dark).length} tokens.`);
